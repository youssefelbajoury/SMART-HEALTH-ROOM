"use client";

import { useEffect } from "react";
import { motion } from "framer-motion";
import { useAlertStore } from "@/store/alertStore";
import { EmptyState } from "@/components/ui/empty-state";
import { Skeleton } from "@/components/ui/skeleton";
import {
  AlertTriangle,
  XCircle,
  Info,
  Check,
  Clock,
} from "lucide-react";

export default function AlertsPage() {
  const { alerts, unreadCount, isLoading, markAsRead, markAllAsRead, fetchAlerts } =
    useAlertStore();

  useEffect(() => {
    fetchAlerts();
  }, [fetchAlerts]);

  const getAlertIcon = (type: string) => {
    switch (type) {
      case "danger":
        return <XCircle className="w-6 h-6 text-red-400" />;
      case "warning":
        return <AlertTriangle className="w-6 h-6 text-orange-400" />;
      default:
        return <Info className="w-6 h-6 text-blue-400" />;
    }
  };

  const getAlertBorder = (type: string) => {
    switch (type) {
      case "danger":
        return "border-red-500/30 bg-red-500/5";
      case "warning":
        return "border-orange-500/30 bg-orange-500/5";
      default:
        return "border-blue-500/30 bg-blue-500/5";
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl sm:text-3xl font-bold text-white day:text-slate-900">
            Alert History
          </h1>
          <p className="text-slate-400 day:text-slate-500 mt-1">
            {unreadCount > 0
              ? `${unreadCount} unread alert${unreadCount > 1 ? "s" : ""}`
              : "All alerts are read"}
          </p>
        </div>
        {unreadCount > 0 && (
          <button
            onClick={markAllAsRead}
            className="flex items-center gap-2 px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg transition-colors text-sm"
          >
            <Check className="w-4 h-4" />
            Mark all as read
          </button>
        )}
      </div>

      <div className="space-y-3">
        {isLoading && alerts.length === 0 ? (
          <>
            {[0, 1, 2].map((i) => (
              <Skeleton key={i} className="h-20 w-full" />
            ))}
          </>
        ) : alerts.length === 0 ? (
          <EmptyState icon={Info} title="No alerts yet" description="Alerts generated by your sensors will appear here." />
        ) : (
          alerts.map((alert, index) => (
            <motion.div
              key={alert.id}
              initial={{ opacity: 0, y: 8 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: index * 0.03 }}
              onClick={() => !alert.read && markAsRead(alert.id)}
              role={!alert.read ? "button" : undefined}
              tabIndex={!alert.read ? 0 : undefined}
              onKeyDown={(e) => {
                if (!alert.read && (e.key === "Enter" || e.key === " ")) {
                  e.preventDefault()
                  markAsRead(alert.id)
                }
              }}
              className={`p-4 rounded-xl border backdrop-blur-md cursor-pointer transition-all hover:scale-[1.01] ${getAlertBorder(alert.type)} ${!alert.read ? "ring-1 ring-indigo-500/30" : "opacity-75"}`}
            >
              <div className="flex items-start gap-4">
                <div className="flex-shrink-0">{getAlertIcon(alert.type)}</div>
                <div className="flex-1 min-w-0">
                  <div className="flex items-start justify-between">
                    <div>
                      <p
                        className={`text-sm font-medium ${!alert.read ? "text-white day:text-slate-900" : "text-slate-300 day:text-slate-500"}`}
                      >
                        {alert.message}
                      </p>
                      <div className="flex items-center gap-3 mt-2 text-xs text-slate-500">
                        <span className="flex items-center gap-1">
                          <Clock className="w-3 h-3" />
                          {new Date(alert.timestamp).toLocaleString("en-US")}
                        </span>
                        <span className="px-2 py-0.5 rounded-full bg-slate-800 text-slate-400 day:bg-slate-100 day:text-slate-500">
                          {alert.sensor}
                        </span>
                        <span>Value: {alert.value}</span>
                      </div>
                    </div>
                    {!alert.read && (
                      <div className="w-2 h-2 bg-indigo-500 rounded-full flex-shrink-0 mt-1" />
                    )}
                  </div>
                </div>
              </div>
            </motion.div>
          ))
        )}
      </div>
    </div>
  );
}
