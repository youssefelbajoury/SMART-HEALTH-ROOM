/// The AI Assistant screen — a deterministic, fully-explainable chat
/// interface. Every answer is generated by `assistant_intents.dart` reading
/// the exact same `HealthScoreResult`/`RoomQualityResult`/`PredictiveWarning`/
/// `AssistantRecommendation` objects Home and Dashboard already render
/// (via the shared `computeDashboardInsights()` helper) — there is no LLM
/// call, so the assistant can never disagree with what's on screen elsewhere.
class AssistantScreen extends StatefulWidget {
  const AssistantScreen({super.key});

  @override
  State<AssistantScreen> createState() => _AssistantScreenState();
}

class _AssistantScreenState extends State<AssistantScreen> {
  final _controller = TextEditingController();
  final _scrollController = ScrollController();
  bool _isListening = false;
  String? _speakingMessageId;

  @override
  void initState() {
    super.initState();
    context.read<ChatProvider>().loadHistory();
  }

  @override
  void dispose() {
    _controller.dispose();
    _scrollController.dispose();
    VoiceService.instance.stopListening();
    VoiceService.instance.stopSpeaking();
    super.dispose();
  }

  void _scrollToBottom() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (!_scrollController.hasClients) return;
      _scrollController.animateTo(
        _scrollController.position.maxScrollExtent,
        duration: const Duration(milliseconds: 300),
        curve: Curves.easeOut,
      );
    });
  }

  Future<void> _send([String? preset]) async {
    final question = preset ?? _controller.text;
    if (question.trim().isEmpty) return;
    _controller.clear();
    FocusScope.of(context).unfocus();
    HapticFeedback.lightImpact();

    final sensor = context.read<SensorProvider>();
    final emergency = context.read<EmergencyProvider>();
    final weather = context.read<WeatherProvider>();
    final data = sensor.data;

    await context.read<ChatProvider>().ask(question, (q) {
      if (data == null) return "I don't have live sensor data yet — please try again shortly.";
      final insights = computeDashboardInsights(
        data: data,
        history: sensor.history,
        weather: weather.weather,
        outdoorAqi: weather.outdoorAqi,
        emergencyActive: emergency.active != null,
        userName: 'there',
      );
      final ctx = AssistantAnswerContext(
        data: data,
        healthScore: insights.healthScore,
        roomQuality: insights.roomQuality,
        predictiveWarning: insights.predictiveWarning,
        recommendations: insights.recommendations,
      );
      return answerQuestion(matchIntent(q), ctx);
    });
    _scrollToBottom();
  }

  Future<void> _toggleListening() async {
    if (_isListening) {
      VoiceService.instance.stopListening();
      setState(() => _isListening = false);
      return;
    }
    HapticFeedback.selectionClick();
    final started = await VoiceService.instance.startListening(
      onResult: (text) => setState(() => _controller.text = text),
      onDone: () => setState(() => _isListening = false),
    );
    if (started) {
      setState(() => _isListening = true);
    } else if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Speech recognition is not available on this device.')),
      );
    }
  }

  Future<void> _speak(String id, String text) async {
    if (_speakingMessageId == id) {
      await VoiceService.instance.stopSpeaking();
      setState(() => _speakingMessageId = null);
      return;
    }
    setState(() => _speakingMessageId = id);
    await VoiceService.instance.speak(text);
    if (mounted) setState(() => _speakingMessageId = null);
  }

  @override
  Widget build(BuildContext context) {
    final chat = context.watch<ChatProvider>();
    final sensor = context.watch<SensorProvider>();
    final themeProvider = context.watch<ThemeProvider>();
    final isDay = themeProvider.resolveIsDay(sensorIsDay: sensor.data?.isDay ?? true);
    final textColor = isDay ? const Color(0xFF0F172A) : Colors.white;
    final grounded = sensor.data != null;

    if (chat.messages.isNotEmpty) _scrollToBottom();

    return Scaffold(
      backgroundColor: isDay ? const Color(0xFFF0F9FF) : const Color(0xFF0F172A),
      appBar: AppBar(
        title: Text('AI Assistant', style: TextStyle(color: textColor, fontWeight: FontWeight.w700)),
        iconTheme: IconThemeData(color: textColor),
        actions: [
          Container(
            margin: const EdgeInsets.only(right: 12),
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 5),
            decoration: BoxDecoration(
              color: (grounded ? AppColors.fine : AppColors.secondary400).withValues(alpha: 0.15),
              borderRadius: BorderRadius.circular(999),
            ),
            child: Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                Container(
                  width: 7,
                  height: 7,
                  decoration: BoxDecoration(
                    color: grounded ? AppColors.fine : AppColors.secondary400,
                    shape: BoxShape.circle,
                  ),
                ),
                const SizedBox(width: 6),
                Text(
                  grounded ? 'Live data' : 'No data',
                  style: TextStyle(fontSize: 11, fontWeight: FontWeight.w600, color: grounded ? AppColors.fine : AppColors.secondary400),
                ),
              ],
            ),
          ),
        ],
      ),
      body: Column(
        children: [
          Expanded(
            child: chat.messages.isEmpty
                ? _buildEmptyState(isDay, textColor)
                : ListView.builder(
                    controller: _scrollController,
                    padding: const EdgeInsets.fromLTRB(14, 14, 14, 6),
                    itemCount: chat.messages.length + (chat.isTyping ? 1 : 0),
                    itemBuilder: (context, index) {
                      if (index == chat.messages.length) {
                        return TypingIndicator(isDay: isDay);
                      }
                      final message = chat.messages[index];
                      return ChatBubble(
                        message: message,
                        isDay: isDay,
                        onSpeak: message.isUser ? null : () => _speak(message.id, message.text),
                        isSpeaking: _speakingMessageId == message.id,
                      );
                    },
                  ),
          ),
          _buildSuggestedQuestions(isDay, textColor),
          _buildInputRow(isDay, textColor),
        ],
      ),
    );
  }

  Widget _buildEmptyState(bool isDay, Color textColor) {
    return Center(
      child: Padding(
        padding: const EdgeInsets.all(32),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(Icons.auto_awesome_rounded, size: 56, color: AppColors.primary400)
                .animate()
                .fadeIn(duration: 400.ms)
                .scale(begin: const Offset(0.8, 0.8)),
            const SizedBox(height: 16),
            Text(
              "Ask me anything about your room",
              textAlign: TextAlign.center,
              style: TextStyle(fontSize: 17, fontWeight: FontWeight.w700, color: textColor),
            ),
            const SizedBox(height: 8),
            Text(
              'Every answer is grounded in your live sensor data — no external AI, fully explainable.',
              textAlign: TextAlign.center,
              style: TextStyle(fontSize: 13, color: textColor.withValues(alpha: 0.6)),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildSuggestedQuestions(bool isDay, Color textColor) {
    return SizedBox(
      height: 42,
      child: ListView.separated(
        scrollDirection: Axis.horizontal,
        padding: const EdgeInsets.symmetric(horizontal: 14),
        itemCount: suggestedQuestions.length,
        separatorBuilder: (context, index) => const SizedBox(width: 8),
        itemBuilder: (context, i) {
          final question = suggestedQuestions[i];
          return ActionChip(
            label: Text(question, style: const TextStyle(fontSize: 12.5)),
            backgroundColor: isDay ? Colors.white : Colors.white.withValues(alpha: 0.06),
            side: BorderSide(color: isDay ? const Color(0xFFE2E8F0) : Colors.white12),
            labelStyle: TextStyle(color: textColor),
            onPressed: () => _send(question),
          );
        },
      ),
    );
  }

  Widget _buildInputRow(bool isDay, Color textColor) {
    return Padding(
      padding: EdgeInsets.fromLTRB(12, 8, 12, 8 + MediaQuery.of(context).padding.bottom),
      child: Row(
        children: [
          IconButton(
            onPressed: _toggleListening,
            icon: Icon(_isListening ? Icons.mic_rounded : Icons.mic_none_rounded),
            color: _isListening ? AppColors.destructive : AppColors.primary500,
            style: IconButton.styleFrom(
              backgroundColor: (_isListening ? AppColors.destructive : AppColors.primary500).withValues(alpha: 0.1),
            ),
          ),
          const SizedBox(width: 6),
          Expanded(
            child: TextField(
              controller: _controller,
              style: TextStyle(color: textColor),
              decoration: InputDecoration(
                hintText: _isListening ? 'Listening…' : 'Ask a question…',
                filled: true,
                fillColor: isDay ? Colors.white : Colors.white.withValues(alpha: 0.06),
                contentPadding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
                border: OutlineInputBorder(borderRadius: BorderRadius.circular(999), borderSide: BorderSide.none),
              ),
              onSubmitted: (_) => _send(),
              textInputAction: TextInputAction.send,
            ),
          ),
          const SizedBox(width: 6),
          IconButton(
            onPressed: () => _send(),
            icon: const Icon(Icons.send_rounded),
            color: Colors.white,
            style: IconButton.styleFrom(backgroundColor: AppColors.primary500),
          ),
        ],
      ),
    );
  }
}
